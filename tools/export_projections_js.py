# -*- coding: utf-8 -*-
"""Export data/map_projections.json -> app/data/projections.js for frontend world->uv projection."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "map_projections.json"
DST = ROOT / "app" / "data" / "projections.js"


def main() -> None:
    raw = json.loads(SRC.read_text(encoding="utf-8"))
    out = {}
    for k, v in sorted(raw.items()):
        out[k] = {
            "camX": v["camX"],
            "camZ": v["camZ"],
            "captureHeight": v["captureHeight"],
            "origW": v["origW"],
            "origH": v["origH"],
            "resizedW": v["resizedW"],
            "resizedH": v["resizedH"],
            "crop": v["crop"],
            "bancNames": v.get("bancNames", []),
        }
    text = (
        "/* Generated by tools/export_projections_js.py - do not edit by hand. */\n"
        "window.OOT_PROJECTIONS = "
        + json.dumps(out, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    DST.write_text(text, encoding="utf-8")
    print(f"Wrote {DST} ({len(out)} regions, {len(text)} bytes)")


if __name__ == "__main__":
    main()
